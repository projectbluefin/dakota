#!/usr/bin/env python3
"""Pin a Ghostty release and its complete Zig dependency graph in ghostty.bst.

Ghostty builds offline, so every package in its dependency graph must be a
BuildStream source. Upstream publishes that graph for packagers as
build.zig.zon.json in the release tarball; this pins each archive by sha256 and
rewrites the release URL, the generated source block, and the version string.
It refuses a release that needs a newer Zig than bluefin/zig.bst provides.

Usage: generate_ghostty_sources.py <version> [element]
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import sys
import tarfile
import tempfile
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
ELEMENT = ROOT / "elements/bluefin/ghostty.bst"
ZIG_ELEMENT = ROOT / "elements/bluefin/zig.bst"
ALIASES = ROOT / "include/aliases.yml"
RELEASE_URL = "https://release.files.ghostty.org/{version}/ghostty-{version}.tar.gz"
BEGIN = "  # BEGIN generated by files/scripts/generate_ghostty_sources.py\n"
END = "  # END generated\n"

# git+ dependencies are pinned to a commit; fetch that commit's archive. Zig
# hashes the unpacked tree, so the archive yields the same package hash.
GIT_ARCHIVES = {
    "github.com": "https://github.com/{repo}/archive/{commit}.tar.gz",
    "codeberg.org": "https://codeberg.org/{repo}/archive/{commit}.tar.gz",
}


def version_tuple(text: str) -> tuple[int, ...]:
    return tuple(int(part) for part in text.split("."))


def load_aliases() -> list[tuple[str, str]]:
    aliases = re.findall(r"^  ([a-z0-9_]+): (https://\S+)$", ALIASES.read_text(), re.MULTILINE)
    # Longest prefix wins, so ghostty_deps beats a generic host alias.
    return sorted(((url, name) for name, url in aliases), key=lambda a: -len(a[0]))


def aliased(url: str, aliases: list[tuple[str, str]]) -> str:
    for prefix, name in aliases:
        if url.startswith(prefix):
            return f"{name}:{url[len(prefix):]}"
    raise ValueError(f"No alias in include/aliases.yml covers {url}")


def archive_url(url: str) -> str:
    if not url.startswith("git+"):
        return url
    match = re.fullmatch(r"git\+https://([^/]+)/([^?#]+?)(?:\.git)?(?:\?[^#]*)?#([0-9a-f]{40})", url)
    if not match or match[1] not in GIT_ARCHIVES:
        raise ValueError(f"Unsupported git dependency (need a pinned commit on a known host): {url}")
    return GIT_ARCHIVES[match[1]].format(repo=match[2], commit=match[3])


def download(url: str, out=None) -> str:
    """Stream url (optionally into out) and return its sha256."""
    request = urllib.request.Request(url, headers={"User-Agent": "dakota-source-generator"})
    digest = hashlib.sha256()
    with urllib.request.urlopen(request, timeout=120) as response:
        while chunk := response.read(1 << 20):
            digest.update(chunk)
            if out is not None:
                out.write(chunk)
    return digest.hexdigest()


def release_metadata(version: str) -> tuple[str, str, dict]:
    """Return the release sha256, minimum Zig version, and dependency graph."""
    with tempfile.TemporaryFile() as tarball:
        sha = download(RELEASE_URL.format(version=version), tarball)
        tarball.seek(0)
        with tarfile.open(fileobj=tarball) as tar:
            prefix = f"ghostty-{version}/"
            zon = tar.extractfile(prefix + "build.zig.zon").read().decode()
            graph = json.load(tar.extractfile(prefix + "build.zig.zon.json"))
    minimum = re.search(r'\.minimum_zig_version\s*=\s*"([^"]+)"', zon)
    if not minimum:
        raise ValueError("Ghostty build.zig.zon declares no minimum_zig_version")
    return sha, minimum[1], graph


def render(graph: dict, aliases: list[tuple[str, str]]) -> str:
    lines = [BEGIN]
    for zig_hash, dep in sorted(graph.items(), key=lambda item: item[1]["name"]):
        url = archive_url(dep["url"])
        lines += [
            f"  # {dep['name']} ({zig_hash})\n",
            "  - kind: remote\n",
            f"    url: {aliased(url, aliases)}\n",
            f"    ref: {download(url)}\n",
            "    directory: zig-deps\n",
            "\n",
        ]
    lines.append(END)
    return "".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) not in (2, 3) or not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", argv[1]):
        print(__doc__, file=sys.stderr)
        return 2
    version = argv[1]
    element = Path(argv[2]) if len(argv) == 3 else ELEMENT
    zig = re.search(r"download/([0-9.]+)/zig-x86_64-linux", ZIG_ELEMENT.read_text())[1]
    release_sha, minimum, graph = release_metadata(version)
    if version_tuple(minimum) > version_tuple(zig):
        raise SystemExit(f"Ghostty {version} needs Zig {minimum}; bluefin/zig.bst has {zig}")

    text = element.read_text()
    start, stop = text.index(BEGIN), text.index(END) + len(END)
    text = text[:start] + render(graph, load_aliases()) + text[stop:]
    text, count = re.subn(r"(url: ghostty_releases:)[0-9.]+/ghostty-[0-9.]+\.tar\.gz\n(\s+ref: )[0-9a-f]{64}",
                          rf"\g<1>{version}/ghostty-{version}.tar.gz\n\g<2>{release_sha}", text)
    text, vcount = re.subn(r"-Dversion-string=[0-9.]+", f"-Dversion-string={version}", text)
    if count != 1 or vcount != 1:
        raise ValueError("Expected exactly one Ghostty release source and one -Dversion-string")
    element.write_text(text)
    print(f"ghostty {version}: {len(graph)} Zig dependencies (Zig >= {minimum})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
